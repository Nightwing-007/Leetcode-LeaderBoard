/**
 * Calculates rank ordering based strictly on LeetCode parameters:
 * 1. Global Rank (lower is better) or Total Solved
 * 2. Max Contests Attended
 * 3. Highest Contest Rating
 */
export function calculateCompositeScore(student) {
  const lcSolved = student.leetcode?.solvedTotal || 0;
  const lcRating = student.leetcode?.contestRating || 1500;
  const lcContests = student.leetcode?.contestAttended || 0;
  const lcRank = student.leetcode?.globalRank || 100000;

  // Composite formula prioritizing contest rating, contests attended, solved count, and lower global rank
  const rankBonus = Math.max(0, 100000 - lcRank) * 0.05;
  const score = (lcRating * 2) + (lcContests * 25) + (lcSolved * 1.5) + rankBonus;
  return Math.round(score);
}
